import { Text, type StyleProp, type TextStyle } from 'react-native';
import { fmtMs, fmtSignedMs, useNow } from '../lib/time';

/**
 * Тикающее время с миллисекундами.
 *
 * Свой таймер на каждый такой показатель, а не общий `now` на весь экран:
 * с миллисекундами тикать надо десятки раз в секунду, и общий счётчик
 * перерисовывал бы вместе с собой весь список упражнений с полями ввода.
 * Здесь перерисовывается ровно одна строка текста.
 *
 * Значение считается из моментов времени, а не накапливается тиками:
 * пропущенные кадры (свёрнутое приложение, занятый поток) на результат не
 * влияют — сколько прошло по часам, столько и покажет.
 */

/** 20 кадров в секунду: миллисекунды бегут заметно, а не дёргаются. */
const TICK_MS = 50;

export function LiveTimer({
  since,
  base = 0,
  until = null,
  signed = false,
  style,
}: {
  /** Момент, от которого идёт отсчёт. Может быть в будущем — тогда
   *  значение отрицательное: это отсчёт ДО начала. */
  since: string | null;
  /** Уже накопленные секунды (или вычтенные, если отрицательные). */
  base?: number;
  /** Момент, на котором время замерло: пауза. NULL — идёт сейчас. */
  until?: string | null;
  /** Показывать ли минус. Без него отрицательное время обрезается нулём. */
  signed?: boolean;
  style?: StyleProp<TextStyle>;
}) {
  // На паузе и до старта тикать незачем — значение всё равно не меняется.
  const now = useNow(since !== null && until === null, TICK_MS);

  const value =
    since === null
      ? base
      : base + ((until === null ? now : Date.parse(until)) - Date.parse(since)) / 1000;

  return (
    <Text
      // моноширинные цифры: иначе строка дёргается на каждом знаке,
      // а с миллисекундами это происходит непрерывно
      style={[{ fontVariant: ['tabular-nums'] }, style]}
    >
      {signed ? fmtSignedMs(value) : fmtMs(value)}
    </Text>
  );
}
