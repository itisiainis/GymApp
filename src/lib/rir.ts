/**
 * RIR — сколько повторов осталось в запасе к концу подхода.
 *
 * Заменил секундомер как способ засчитать подход на повторы: время
 * подхода на повторы почти ничего не говорит о нагрузке, а «сколько ещё
 * мог» — говорит. Секундомер никуда не делся, но стал необязательным
 * режимом (`advancedReps` в db/settings.ts); холды меряются временем
 * всегда.
 *
 * Шкала идёт слева направо на убывание: «>5» и дальше 5, 4, 3, 2, 1, 0 —
 * от «легко» к «до отказа». Ноль — край, дальше запаса нет.
 */

/** Значение шкалы: 0–5 либо 6 — то самое «>5». */
export type RirValue = number;

/**
 * «Больше пяти» хранится числом 6: это не отдельная категория, а тот же
 * счёт с открытым верхом. Для анализа — цензура сверху, а не пропуск,
 * поэтому колонка остаётся обычным числом (см. db/backup.ts).
 */
export const RIR_OPEN = 6;

/** Порядок в барабане. */
export const RIR_OPTIONS: RirValue[] = [RIR_OPEN, 5, 4, 3, 2, 1, 0];

/**
 * Значение, на котором барабан стоит, пока подход не записан. Не «пусто»
 * и не отдельный слот: «ещё много» — это осмысленное положение шкалы, и
 * начинать с него честнее, чем с прочерка. Что подход ещё не записан,
 * видно по цвету, а не по значению.
 */
export const RIR_DEFAULT = RIR_OPEN;

/** Строка подхода в той части, что касается RIR. */
export interface RirRow {
  rir: number | null;
}

/** Значение подхода. null — RIR не проставлен. */
export function rirOf(row: RirRow): RirValue | null {
  return row.rir;
}

/** Проставлен ли RIR — то же, что «подход записан» в режиме без секундомера. */
export function hasRir(row: RirRow): boolean {
  return row.rir !== null;
}

/** Подпись значения: 6 показывается как «>5». */
export function rirLabel(v: RirValue): string {
  return v >= RIR_OPEN ? '>5' : String(v);
}

/**
 * Подпись для истории и разбора: там подход показан одной строкой, и
 * число нужно с пояснением, что это за число. null — показывать нечего.
 */
export function rirBadge(row: RirRow, t: (key: string) => string): string | null {
  const v = rirOf(row);
  return v === null ? null : `${t('RIR')} ${rirLabel(v)}`;
}
