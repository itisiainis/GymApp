/**
 * Поиск упражнений по тегам.
 *
 * Тег — это мышца упражнения или его снаряд: «бицепс», «штанга». Отдельно
 * их заводить не надо, они и так уже заданы при создании упражнения —
 * поиск просто начинает их видеть.
 *
 * Фильтрация живёт здесь, а не в SQL, ровно по одной причине: названия
 * мышц и снарядов лежат в базе каноническими английскими, а переводит их
 * только интерфейс. LIKE по базе нашёл бы «Chest», но не «грудь». Здесь
 * же под рукой t(), поэтому ищется и то и другое.
 */

/** То, что нужно от упражнения для поиска. */
export interface Taggable {
  name: string;
  /** Канонические названия мышц и снаряда через запятую. */
  tags: string | null;
}

/** Теги упражнения списком, уже переведённые. */
export function exerciseTags(ex: Taggable, t: (key: string) => string): string[] {
  if (!ex.tags) return [];
  return ex.tags
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map(t);
}

/**
 * Подходит ли упражнение под запрос. Пустой запрос подходит всему.
 *
 * Слова запроса проверяются по отдельности и все вместе: «бицепс штанга»
 * находит упражнение, у которого есть оба тега, в любом порядке. Иначе
 * пришлось бы угадывать, как именно составлен тег.
 */
export function matchesQuery(
  ex: Taggable,
  query: string,
  t: (key: string) => string
): boolean {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return true;

  // и канонические названия, и переводы: искать хочется на том языке, на
  // котором приложение сейчас говорит, но и английское название рабочее
  const haystack = [ex.name, ...exerciseTags(ex, t), ...(ex.tags ?? '').split(',')]
    .join(' ')
    .toLowerCase();

  return words.every((w) => haystack.includes(w));
}
