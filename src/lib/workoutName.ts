/**
 * Имя тренировки, собранной с нуля.
 *
 * Шаблон перестал быть обязательным, и у тренировки с нуля названия
 * взять неоткуда — его собирают по главным мышцам входящих упражнений:
 * «Chest + Triceps». Пересчитывается по мере добавления упражнений
 * (см. refreshWorkoutName в db/workout-session.ts).
 */

/** Чем склеены мышцы в имени. По нему же оно разбирается обратно. */
export const NAME_SEPARATOR = ' + ';

/**
 * В базе имя лежит из канонических (английских) названий мышц — тех же,
 * что в таблице muscles. Иначе смена языка замораживала бы старые имена
 * на языке, который стоял в момент записи. Переводим при показе, по
 * кусочкам: t() знает каждую мышцу по отдельности.
 *
 * Имя, введённое руками (шаблон), через t() просто проходит насквозь —
 * в словаре его нет, и он вернёт его как есть.
 */
export function localizeWorkoutName(
  name: string | null,
  t: (key: string) => string
): string | null {
  if (name === null) return null;
  return name.split(NAME_SEPARATOR).map(t).join(NAME_SEPARATOR);
}
