/**
 * Настоящая нагрузка подхода.
 *
 * В подходе записывают то, что написано на снаряде: вес ОДНОЙ гантели,
 * блин на поясе. Сколько при этом поднято на самом деле — считается из
 * снаряжения упражнения (см. таблицу equipment в db/migrations.ts):
 * пара гантелей удваивает введённый вес, упражнения с собственным весом
 * прибавляют вес тела.
 *
 * Правило хранится данными, а не разбором названий: «если снаряд
 * называется гантели, то умножить на два» разъехалось бы с первым же
 * переименованием или переводом.
 */

/** Часть строки упражнения, от которой зависит арифметика веса. */
export interface LoadRule {
  /** На что умножается введённый вес. У пары гантелей — 2. */
  weight_factor: number | null;
  /** 1 — к нагрузке прибавляется вес тела. */
  adds_bodyweight: number | null;
}

/**
 * Сколько поднято на самом деле, в килограммах.
 *
 * null — показывать нечего: вес не введён и телом упражнение не грузится.
 * Вес тела, которого нет в истории (bodyweightKg === null), молча не
 * прибавляем: выдумывать его нельзя, а показать введённое всё равно
 * лучше, чем ничего.
 */
export function effectiveLoad(
  weightKg: number | null,
  rule: LoadRule,
  bodyweightKg: number | null
): number | null {
  const own = rule.adds_bodyweight === 1 ? (bodyweightKg ?? 0) : 0;
  if (weightKg === null && own === 0) return null;
  return (weightKg ?? 0) * (rule.weight_factor ?? 1) + own;
}

/** Килограммы без хвоста из нулей: 40, 42.5. */
export function fmtKg(kg: number): string {
  return String(Math.round(kg * 100) / 100);
}
